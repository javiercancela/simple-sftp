// Generates THIRD_PARTY_NOTICES.md from the production dependency tree
// (`npm ls --omit=dev`) plus the Electron runtime that ships in every package.
// Usage: node scripts/generate-notices.mjs [--check]
//   --check: exit 1 if the committed file is out of date.
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = join(ROOT, 'THIRD_PARTY_NOTICES.md');

const tree = JSON.parse(
  execFileSync('npm', ['ls', '--omit=dev', '--all', '--json', '--long'], {
    cwd: ROOT,
    encoding: 'utf8',
    shell: process.platform === 'win32',
    maxBuffer: 64 * 1024 * 1024,
  }),
);
const found = new Map();
(function walk(deps) {
  for (const [name, d] of Object.entries(deps ?? {})) {
    if (d.path && !found.has(`${name}@${d.version}`)) found.set(`${name}@${d.version}`, d.path);
    walk(d.dependencies);
  }
})(tree.dependencies);
// The runtime: Electron (devDependency, but its binaries are the app's shell).
const electronDir = join(ROOT, 'node_modules', 'electron');
const electronVersion = JSON.parse(readFileSync(join(electronDir, 'package.json'), 'utf8')).version;
found.set(`electron@${electronVersion}`, electronDir);

function licenseText(dir) {
  const files = readdirSync(dir).filter((f) => /^(licen[cs]e|copying|notice)([._-].*)?$/i.test(f));
  return files.map((f) => readFileSync(join(dir, f), 'utf8').trim()).join('\n\n');
}

const patched = new Set(
  existsSync(join(ROOT, 'patches'))
    ? readdirSync(join(ROOT, 'patches')).map((f) =>
        f.replace(/\+[^+]*\.patch$/, '').replace('+', '/'),
      )
    : [],
);
const entries = [...found.entries()]
  .map(([id, dir]) => {
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
    return {
      id,
      name: pkg.name,
      license:
        pkg.license ??
        (Array.isArray(pkg.licenses) ? pkg.licenses.map((l) => l.type).join(' OR ') : 'UNKNOWN'),
      repo,
      text: licenseText(dir),
    };
  })
  .sort((a, b) => a.id.localeCompare(b.id));

let md = `# Third-party notices

SimpleSFTP includes the following third-party software. This file is
generated by \`node scripts/generate-notices.mjs\` from the production
dependency tree (\`npm ls --omit=dev\`) plus the Electron runtime; do not edit
it by hand. Packaged builds also contain Electron's \`LICENSE\` and
\`LICENSES.chromium.html\` (Chromium and its dependencies) next to the
executable.

| Package | License | Notes |
| --- | --- | --- |
`;
for (const e of entries) {
  const notes = [
    patched.has(e.name) ? 'modified: see `patches/`' : '',
    e.name === 'electron' ? 'runtime (Chromium + Node.js)' : '',
  ]
    .filter(Boolean)
    .join('; ');
  md += `| ${e.id} | ${e.license} | ${notes} |\n`;
}
for (const e of entries) {
  md += `\n## ${e.id}\n\nLicense: ${e.license}${e.repo ? `  \nSource: ${e.repo.replace(/^git\+/, '')}` : ''}\n\n`;
  md += e.text
    ? `\`\`\`text\n${e.text.replace(/```/g, "'''")}\n\`\`\`\n`
    : '_No license file in the published package; see the license field above._\n';
}

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== md) {
    console.error('THIRD_PARTY_NOTICES.md is out of date: run node scripts/generate-notices.mjs');
    process.exit(1);
  }
  console.log(`THIRD_PARTY_NOTICES.md is up to date (${entries.length} packages).`);
} else {
  writeFileSync(OUT, md);
  console.log(`Wrote THIRD_PARTY_NOTICES.md (${entries.length} packages).`);
}
